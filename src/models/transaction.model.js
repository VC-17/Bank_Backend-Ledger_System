import mongoose from 'mongoose';

const transactionSchema = new mongoose.Schema({
    fromAccount : {
        type : mongoose.Schema.Types.ObjectId,
        ref : "Account",
        required : [true , "Transaction must be associated with a from account"],
        index : true
    },
    toAccount : {
        type : mongoose.Schema.Types.ObjectId,
        ref : "Account",
        required : [true , "Transaction must be associated with a from account"],
        index : true
    },
    status : {
        type : String ,
        enum : {
            values : ["PENDING","COMPLETED","FAILED","REVERSED"],
            message : "Status can be either PENDING , COMPLETED , FAILED , REVERSED"
        },
        default : "PENDING"
    },
    amount : {
        type : Number ,
        required : [true , "Amount is required for creating a transaction"],
        min : [0 , "Transaction amount cannot be negative"]
    },

    // The idempotencyKey field is used to ensure that a transaction is only processed once, 
    // even if the same request is sent multiple times. This is important in scenarios where 
    // network issues or client retries may result in duplicate requests. By using a unique 
    // idempotency key for each transaction request, the server can recognize and ignore duplicate 
    // requests, preventing unintended duplicate transactions.
    //The idempotencyKey is typically generated by the client and sent along with the transaction request.
    idempotencyKey : {
        type : String ,
        required : [true , "IdempotencyKey is required for creating a transaction"],
        index : true ,
        unique : true
    }
},{timestamps:true})

export const transactionModel = mongoose.model("transaction",transactionSchema)